def make_slug(front, title):
    custom = front.get("slug")
    if isinstance(custom, str) and custom.strip():
        return re.sub(r"[^a-z0-9-]", "", custom.strip().lower()) or "post"
    digest = hashlib.md5(title.encode("utf-8")).hexdigest()[:8]
    return "a-" + digest


def format_date(front, md_path, body=""):
    """日期优先级：frontmatter 的 created/date → 正文里的「原文日期：…」 → 文件修改时间。"""
    raw = front.get("created") or front.get("date") or ""
    if isinstance(raw, list):
        raw = raw[0] if raw else ""
    found = match_date(str(raw))
    if found:
        return found
    snippet = body[:1200]
    m = re.search(r"原文日期[:：]\s*(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日", snippet)
    if not m:
        m = re.search(r"(?<!\d)(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日", snippet)
    if m:
        return "%04d-%02d-%02d" % (int(m.group(1)), int(m.group(2)), int(m.group(3)))
    stamp = os.path.getmtime(md_path)
    return datetime.datetime.fromtimestamp(stamp).strftime("%Y-%m-%d")


def match_date(text):
    m = re.match(r"(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})", text)
    if m:
        return "%04d-%02d-%02d" % (int(m.group(1)), int(m.group(2)), int(m.group(3)))
    return None


def collect(keywords):
    """扫描源目录，返回符合条件文章的原始信息列表。"""
    src_dir = os.path.join(VAULT_ARTICLES_DIR, SOURCE_SUBDIR)
    if not os.path.isdir(src_dir):
        print("× 找不到文章源目录：%s" % src_dir)
        sys.exit(1)

    found, skipped = [], []
    for root, dirs, files in os.walk(src_dir):
        dirs[:] = [d for d in dirs if d not in ("attachments", ".obsidian", ".trash")]
        for name in sorted(files):
            if not name.lower().endswith(".md"):
                continue
            if keywords and not any(k in name for k in keywords):
                continue
            path = os.path.join(root, name)
            front, body = split_frontmatter(read_text(path))
            status = front.get("status") or ""
            if isinstance(status, list):
                status = status[0] if status else ""
            if status != WANT_STATUS and front.get("web") not in ("true", True):
                skipped.append((name, status or "无 status"))
                continue
            title = front.get("title") if isinstance(front.get("title"), str) else None
            title = (title or first_heading(body) or os.path.splitext(name)[0]).strip()
            found.append({
                "path": path,
                "front": front,
                "body": body,
                "title": title,
                "date": format_date(front, path, body),
                "slug": make_slug(front, title),
            })
    # 同名文章（标题相同）会算出相同 slug，按文件路径再补一小段哈希区分，避免互相覆盖
    seen = set()
    for doc in found:
        slug = doc["slug"]
        if slug in seen:
            slug = "%s-%s" % (slug, hashlib.md5(doc["path"].encode("utf-8")).hexdigest()[:4])
            n = 2
            while slug in seen:
                slug = "%s-%d" % (doc["slug"], n)
                n += 1
        doc["slug"] = slug
        seen.add(slug)
    return found, skipped


def sync_one(doc):
    art_dir = os.path.join(ARTICLES_DIR)
    if not os.path.isdir(art_dir):
        os.makedirs(art_dir)

    summary = doc["front"].get("summary")
    if isinstance(summary, list):
        summary = ""
    body_html, first_img, paras = convert_body(
        doc["body"], os.path.dirname(doc["path"]), doc["slug"], doc["title"]
    )
    if not (isinstance(summary, str) and summary.strip()):
        longer = [p for p in paras if len(p) >= 24]
        summary = (longer or paras or [""])[0]
    summary = re.sub(r"\s+", " ", summary).strip()
    if len(summary) > 64:
        summary = summary[:64] + "…"

    cover = doc["front"].get("cover")
    if not (isinstance(cover, str) and cover.strip()):
        cover = first_img or ""

    html = (
        page_head(
            "%s ｜ %s" % (doc["title"], SITE_NAME),
            summary or SITE_TAGLINE,
            "../assets/css/site.css",
        )
        + topbar_html("../", "articles")
        + ARTICLE_TPL.format(
            title=html_lib.escape(doc["title"]),
            date=doc["date"],
            body=body_html,
        )
        + page_foot("../assets/js/site.js")
        + "\n" + GENERATED_MARK + "\n"
    )
    out_path = os.path.join(ARTICLES_DIR, doc["slug"] + ".html")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html)

    doc["summary"] = summary
    doc["cover"] = cover
    return doc


def write_list_page(items):
    rows = []
    for it in items:
        thumb_html = ""
        if it["cover"]:
            thumb_html = (
                '<div class="ps-item__thumb"><img src="%s" alt="" loading="lazy"></div>'
                % html_lib.escape(it["cover"], quote=True)
            )
        rows.append(LIST_ITEM_TPL.format(
            url=it["slug"] + ".html",
            thumb=thumb_html,
            date=it["date"],
            title=html_lib.escape(it["title"]),
            summary=html_lib.escape(it["summary"]),
        ))
    html = (
        page_head("文章 ｜ %s" % SITE_NAME, "我写过的文章。", "../assets/css/site.css")
        + topbar_html("../", "articles")
        + LIST_TPL.format(
            count=len(items),
            items="\n".join(rows) if rows else '    <li class="ps-item"><p class="ps-item__summary">还没有同步文章。</p></li>',
        )
        + page_foot("../assets/js/site.js")
        + "\n" + GENERATED_MARK + "\n"
    )
    with open(os.path.join(ARTICLES_DIR, "index.html"), "w", encoding="utf-8") as f:
        f.write(html)


def write_data_js(items):
    lines = ["/* 由 tools/sync_articles.py 自动生成，请勿手改 */", "window.PS_ARTICLES = ["]
    for it in items:
        lines.append("  {")
        lines.append('    title: %s,' % js_str(it["title"]))
        lines.append('    date: %s,' % js_str(it["date"]))
        lines.append('    summary: %s,' % js_str(it["summary"]))
        lines.append('    url: %s,' % js_str("articles/" + it["slug"] + ".html"))
        lines.append('    cover: %s' % js_str(it["cover"]))
        lines.append("  },")
    lines.append("];")
    with open(DATA_JS, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def js_str(value):
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def cleanup_orphans(slugs):
    """删掉以前生成、现在已不在清单里的文章页。"""
    if not os.path.isdir(ARTICLES_DIR):
        return
    for name in os.listdir(ARTICLES_DIR):
        if not name.endswith(".html") or name == "index.html":
            continue
        path = os.path.join(ARTICLES_DIR, name)
        if name[:-5] in slugs:
            continue
        try:
            with open(path, "r", encoding="utf-8") as f:
                if GENERATED_MARK in f.read(4000):
                    os.remove(path)
                    print("  – 移除过期文章页 %s" % name)
        except OSError:
            pass


def main():
    keywords = [a for a in sys.argv[1:] if not a.startswith("-")]
    partial = bool(keywords)

    print("读取文章源：%s/%s" % (VAULT_ARTICLES_DIR, SOURCE_SUBDIR))
    docs, skipped = collect(keywords)
    if not docs:
        print("× 没有找到符合条件（status: %s）的文章。" % WANT_STATUS)
    else:
        docs.sort(key=lambda d: (d["date"], d["title"]), reverse=True)
        for doc in docs:
            sync_one(doc)
            print("  ✓ %s  →  articles/%s.html" % (doc["title"], doc["slug"]))

    write_list_page(docs)
    write_data_js(docs)
    print("  ✓ 生成列表页 web/articles/index.html")
    print("  ✓ 生成数据文件 web/assets/js/articles-data.js")

    if not partial:
        cleanup_orphans(set(d["slug"] for d in docs))
    else:
        print("（试水模式：只处理上面这些文章，没有清理其它旧页面）")

    if skipped:
        print("\n跳过的 %d 篇（status 不是「已发布」）：" % len(skipped))
        for name, status in skipped[:12]:
            print("  · %s（%s）" % (name, status))
        if len(skipped) > 12:
            print("  · …还有 %d 篇" % (len(skipped) - 12))

    if WARNINGS:
        print("\n提醒：")
        for w in WARNINGS:
            print("  ! %s" % w)

    print("\n完成。")


if __name__ == "__main__":
    main()
