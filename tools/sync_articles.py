def image_size(path):
    """纯 Python 读 PNG / JPEG / GIF 的宽高，失败返回 (None, None)。"""
    try:
        with open(path, "rb") as f:
            head = f.read(32)
            if head[:8] == b"\x89PNG\r\n\x1a\n":
                w, h = struct.unpack(">II", head[16:24])
                return w, h
            if head[:6] in (b"GIF87a", b"GIF89a"):
                w, h = struct.unpack("<HH", head[6:10])
                return w, h
            if head[:2] == b"\xff\xd8":
                f.seek(2)
                while True:
                    b = f.read(1)
                    if not b:
                        return None, None
                    if b != b"\xff":
                        continue
                    marker = f.read(1)
                    while marker == b"\xff":
                        marker = f.read(1)
                    if not marker:
                        return None, None
                    code = marker[0]
                    if code in (0xD8, 0x01) or 0xD0 <= code <= 0xD7:
                        continue
                    seg = f.read(2)
                    if len(seg) < 2:
                        return None, None
                    length = struct.unpack(">H", seg)[0]
                    if 0xC0 <= code <= 0xCF and code not in (0xC4, 0xC8, 0xCC):
                        info = f.read(5)
                        if len(info) < 5:
                            return None, None
                        h, w = struct.unpack(">HH", info[1:5])
                        return w, h
                    f.seek(length - 2, 1)
    except Exception:
        return None, None
    return None, None


def sniff_ext(path):
    """看文件头判断图片格式，返回扩展名。"""
    try:
        with open(path, "rb") as f:
            head = f.read(12)
    except OSError:
        return ".jpg"
    if head[:8] == b"\x89PNG\r\n\x1a\n":
        return ".png"
    if head[:2] == b"\xff\xd8":
        return ".jpg"
    if head[:6] in (b"GIF87a", b"GIF89a"):
        return ".gif"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return ".webp"
    return ".jpg"


def png_has_alpha(path):
    try:
        with open(path, "rb") as f:
            head = f.read(26)
    except OSError:
        return False
    return head[:8] == b"\x89PNG\r\n\x1a\n" and head[25] in (4, 6)


def sips(args):
    """调用 macOS 自带的 sips；失败就安静放过。"""
    try:
        subprocess.run(
            ["sips"] + args,
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        return True
    except Exception:
        return False


def optimize_image(path):
    """
    把图片压到站内可接受的大小（长边 ≤ 2000px、尽量 ≤ 500KB）。
    只动网站里的副本，不碰 Obsidian 原图。返回最终文件路径（可能换了扩展名）。
    """
    if not shutil.which("sips"):
        return path
    w, h = image_size(path)
    if w and h and max(w, h) > 2000:
        sips(["-Z", "2000", path])
    if os.path.getsize(path) <= 500 * 1024:
        return path
    if png_has_alpha(path):
        return path                     # 带透明的图不转 JPEG，只缩边
    jpg = os.path.splitext(path)[0] + ".jpg"
    if os.path.abspath(jpg) == os.path.abspath(path):
        # 已经是 JPEG：重压到临时文件，更小才替换（直接输出同名会把原图删掉）
        tmp = path + ".opt.jpg"
        ok = sips(["-s", "format", "jpeg", "-s", "formatOptions", "80",
                   "-Z", "2000", path, "--out", tmp])
        if ok and os.path.isfile(tmp) and os.path.getsize(tmp) < os.path.getsize(path):
            os.replace(tmp, path)
        elif os.path.isfile(tmp):
            os.remove(tmp)
        return path
    if sips(["-s", "format", "jpeg", "-s", "formatOptions", "80", "-Z", "2000", path, "--out", jpg]):
        if os.path.isfile(jpg) and os.path.getsize(jpg) < os.path.getsize(path):
            os.remove(path)
            return jpg
        if os.path.isfile(jpg):
            os.remove(jpg)
    return path


def site_image_url(slug, filename):
    return "../assets/img/articles/%s/%s" % (slug, quote(filename))


def copy_image(src, slug):
    """把本地图片复制进 web/assets/img/articles/<slug>/，返回站内相对路径。"""
    name = os.path.basename(src)
    dest_dir = os.path.join(IMG_DIR, slug)
    if not os.path.isdir(dest_dir):
        os.makedirs(dest_dir)
    dest = os.path.join(dest_dir, name)
    if (not os.path.exists(dest)) or os.path.getmtime(src) > os.path.getmtime(dest):
        shutil.copy2(src, dest)
        dest = optimize_image(dest)
    warn_if_big(dest)
    return site_image_url(slug, os.path.basename(dest))


def download_image(url, slug):
    """把外链图片（如公众号的 mmbiz）下载进站，避免外站失效或防盗链。"""
    clean = html_lib.unescape(url).split("#")[0]
    digest = hashlib.md5(clean.encode("utf-8")).hexdigest()[:10]
    dest_dir = os.path.join(IMG_DIR, slug)
    if not os.path.isdir(dest_dir):
        os.makedirs(dest_dir)
    for name in sorted(os.listdir(dest_dir)):
        if name.startswith("web-" + digest + "."):
            cached = optimize_image(os.path.join(dest_dir, name))   # 首次可能没压成功，这里补压
            warn_if_big(cached)
            return site_image_url(slug, os.path.basename(cached))
    tmp = os.path.join(dest_dir, "web-%s.part" % digest)
    req = urllib.request.Request(
        clean,
        headers={
            "User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)",
            "Referer": "https://mp.weixin.qq.com/",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=20) as resp, open(tmp, "wb") as f:
            shutil.copyfileobj(resp, f)
    except Exception:
        if os.path.exists(tmp):
            os.remove(tmp)
        warn("外链图片下载失败，已保留原链接：%s" % clean[:80])
        return html_lib.escape(url, quote=True)
    dest = os.path.join(dest_dir, "web-%s%s" % (digest, sniff_ext(tmp)))
    os.rename(tmp, dest)
    dest = optimize_image(dest)
    warn_if_big(dest)
    return site_image_url(slug, os.path.basename(dest))


def warn_if_big(path):
    if os.path.getsize(path) > 500 * 1024:
        warn(
            "图片仍偏大（%d KB）：%s —— 建议在 Obsidian 里换一张更小的图"
            % (os.path.getsize(path) // 1024, os.path.relpath(path, PROJECT_ROOT))
        )


