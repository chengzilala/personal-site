NOISE_TEXT = re.compile(
    r"^\s*(暂无评论|点赞|在看|分享|收藏|写留言|预览时标签不可点|"
    r"点击上方.{0,10}关注|扫码关注|长按识别|阅读原文)\s*$"
)
META_LINE = re.compile(
    r"^\s*\*\*\s*(题图标题|题图说明|题图|封面|创作者|作者|AI\s*算法提供|算法提供|Prompt|图片来源)\s*\*\*\s*[:：]?"
)
META_DATE = re.compile(r"^\s*[（(]?\s*(原文日期|首发日期|发布日期|发布时间|文章日期)\s*[:：]")
WIKI_IMG = re.compile(r"!\[\[([^\[\]]+?)\]\]")
MD_IMG = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)\)")
ONLY_IMG = re.compile(r"^\s*!\[[^\]]*\]\(([^)\s]+)\)\s*$")
WIKI_LINK = re.compile(r"\[\[([^\[\]]+?)\]\]")
FENCE = re.compile(r"^\s*(```|~~~)")


def norm_escape(text, quote=True):
    """先解掉源文里已有的 HTML 实体，再统一转义，避免出现 &amp;amp; 这种双重转义。"""
    return html_lib.escape(html_lib.unescape(text), quote=quote)


def convert_body(raw, md_dir, slug, title):
    """把正文 markdown 转成 HTML 片段，返回 (html, first_image_url, summary_candidates)。"""
    state = {"first_img": None, "paras": []}

    def resolve_image(target):
        target = target.strip()
        if target.startswith("../assets/"):
            return target            # 已经解析过的站内路径（如引用块二次处理）
        if re.match(r"^(https?:)?//", target):
            return download_image(target, slug)
        if target.startswith("data:"):
            return None
        candidates = [
            os.path.join(md_dir, target),
            os.path.join(VAULT_ARTICLES_DIR, target),
            os.path.join(os.path.dirname(VAULT_ARTICLES_DIR), target),
        ]
        src = next((c for c in candidates if os.path.isfile(c)), None)
        if src is None:
            warn("找不到插图：%s（文章：%s）" % (target, title))
            return None
        url = copy_image(src, slug)
        if state["first_img"] is None:
            state["first_img"] = url
        return url

    def repl_wiki_img(m):
        target = m.group(1).split("|")[0].strip()
        url = resolve_image(target)
        return "" if url is None else "![](%s)" % url

    def repl_md_img(m):
        alt, src = m.group(1), m.group(2)
        if src.startswith("data:"):
            return ""            # 公众号导出带的 1px 占位图，丢掉
        url = resolve_image(src)
        if url is None:
            return "" if not alt else alt
        return "![%s](%s)" % (alt, url)

    def inline(text):
        stash = []

        def keep(fragment):
            stash.append(fragment)
            return "\x00%d\x00" % (len(stash) - 1)

        text = WIKI_LINK.sub(
            lambda m: keep(norm_escape(wiki_label(m.group(1)), quote=False)), text
        )
        text = MD_IMG.sub(lambda m: keep(img_tag(m.group(2), m.group(1))), text)
        text = re.sub(
            r"\[([^\]]+)\]\(([^)\s]+)\)",
            lambda m: keep(
                '<a href="%s" target="_blank" rel="noopener">%s</a>'
                % (norm_escape(m.group(2)), norm_escape(m.group(1), quote=False))
            ),
            text,
        )
        s = html_lib.escape(text, quote=False)
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<!\*)\*([^*\n]+)\*(?!\*)", r"<em>\1</em>", s)
        s = re.sub(r"(?<![\w_])_([^_\n]+)_(?![\w_])", r"<em>\1</em>", s)
        for index, fragment in enumerate(stash):
            s = s.replace("\x00%d\x00" % index, fragment)
        return s

    def img_tag(url, alt):
        alt = alt.strip() or title
        extra = ""
        local = os.path.normpath(os.path.join(ARTICLES_DIR, url))
        if os.path.isfile(local):
            w, h = image_size(local)
            if w and h:
                extra = ' width="%d" height="%d"' % (w, h)
        return '<img src="%s" alt="%s"%s loading="lazy">' % (
            norm_escape(url), norm_escape(alt), extra)

    lines = raw.splitlines()
    blocks = []
    paragraph = []

    def flush_paragraph():
        if not paragraph:
            return
        text = "<br>".join(paragraph)
        blocks.append("<p>%s</p>" % inline(text))
        plain = plain_text(" ".join(paragraph))
        if len(plain) >= 12 and not re.match(r"^(大家好|我是\s*Chester|背景[:：])", plain):
            state["paras"].append(plain)
        paragraph[:] = []

    i = 0
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        # 公众号导出噪声
        if NOISE_TEXT.match(stripped):
            flush_paragraph()
            i += 1
            continue
        if META_LINE.match(stripped) or META_DATE.match(stripped):
            flush_paragraph()
            i += 1
            continue
        if "data:image/svg+xml" in line:
            flush_paragraph()
            i += 1
            continue

        # 「版本管理」这类 callout：整块丢掉
        if re.match(r"^\s*>\s*\[!", line) and re.search(r"(版本管理|内部|草稿|待办)", line):
            flush_paragraph()
            while i < len(lines) and lines[i].lstrip().startswith(">"):
                i += 1
            continue

        # 图片/链接预处理
        line = WIKI_IMG.sub(repl_wiki_img, line)
        line = MD_IMG.sub(repl_md_img, line)
        stripped = line.strip()

        if not stripped:
            flush_paragraph()
            i += 1
            continue

        # 整行只有一张图 → 单独成块，不跟正文挤在一段里
        only_img = ONLY_IMG.match(line)
        if only_img:
            flush_paragraph()
            blocks.append("<figure>%s</figure>" % img_tag(only_img.group(1), ""))
            i += 1
            continue

        # 代码块
        if FENCE.match(line):
            flush_paragraph()
            fence = FENCE.match(line).group(1)
            i += 1
            code = []
            while i < len(lines) and not lines[i].strip().startswith(fence):
                code.append(lines[i])
                i += 1
            i += 1
            blocks.append(
                "<pre><code>%s</code></pre>" % html_lib.escape("\n".join(code), quote=False)
            )
            continue

        # 分隔线（连续多条只留一条）
        if re.match(r"^\s*(-{3,}|\*{3,}|_{3,})\s*$", line):
            flush_paragraph()
            if blocks and blocks[-1] != "<hr>":
                blocks.append("<hr>")
            i += 1
            continue

        # 标题
        heading = re.match(r"^(#{1,6})\s+(.*)$", stripped)
        if heading:
            flush_paragraph()
            level = len(heading.group(1))
            text = heading.group(2).strip()
            if level == 1 and plain_text(text) == plain_text(title):
                i += 1          # 页面顶部已显示标题，正文里不重复
                continue
            if level == 1:
                i += 1
                continue
            blocks.append("<h%d>%s</h%d>" % (level, inline(text), level))
            i += 1
            continue

        # 引用
        if stripped.startswith(">"):
            flush_paragraph()
            quote = []
            while i < len(lines) and lines[i].lstrip().startswith(">"):
                quote.append(re.sub(r"^\s*>\s?", "", lines[i]))
                i += 1
            inner = convert_body("\n".join(quote), md_dir, slug, title)[0]
            blocks.append("<blockquote>%s</blockquote>" % inner.replace("<p>", "").replace("</p>", ""))
            continue

        # 列表
        if re.match(r"^\s*[-*+]\s+", line):
            flush_paragraph()
            items = []
            while i < len(lines):
                m = re.match(r"^\s*[-*+]\s+(.*)$", lines[i])
                if not m:
                    break
                items.append("<li>%s</li>" % inline(m.group(1)))
                i += 1
            blocks.append("<ul>%s</ul>" % "".join(items))
            continue

        if re.match(r"^\s*\d+[.)]\s+", line):
            flush_paragraph()
            items = []
            while i < len(lines):
                m = re.match(r"^\s*\d+[.)]\s+(.*)$", lines[i])
                if not m:
                    break
                items.append("<li>%s</li>" % inline(m.group(1)))
                i += 1
            blocks.append("<ol>%s</ol>" % "".join(items))
            continue

        paragraph.append(line.strip())
        i += 1

    flush_paragraph()
    return "\n".join(blocks), state["first_img"], state["paras"]


def wiki_label(target):
    if "|" in target:
        return target.split("|", 1)[1].strip()
    return target.split("/")[-1].strip()


